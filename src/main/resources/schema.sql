-- Histórico de preços (UC09): uma linha cada vez que o preço de uma loja muda para um produto.
-- O produto é identificado pelo id do Mercado Livre, que não muda quando o servidor reinicia.
CREATE TABLE IF NOT EXISTS historico_preco (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_externo_produto VARCHAR(64)    NOT NULL,
    loja               VARCHAR(200)   NOT NULL,
    preco              NUMERIC(12, 2) NOT NULL,
    registrado_em      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_historico_preco_produto ON historico_preco (id_externo_produto, registrado_em);
